import type {
  Catalog,
  Product,
  QuantityTier,
  Variant,
} from "../shared/domain";
type SeedVariant = [name: string, price: number, id?: string, quantityTiers?: QuantityTier[]];
const variants = (values: SeedVariant[]): Variant[] =>
  values.map(([name, price, id, quantityTiers], i) => ({
    id: id ?? `v${i}`, name, price,
    ...(quantityTiers ? { quantityTiers } : {}),
  }));
function product(
  id: string,
  name: string,
  categoryId: string,
  description: string,
  image: string,
  values: SeedVariant[],
  featured = false,
  badge = "",
): Product {
  return {
    id,
    name,
    categoryId,
    description,
    ingredients: "",
    image: `/media/${image}`,
    variants: variants(values),
    available: true,
    archived: false,
    featured,
    badge,
    kind: "product",
    groups: [],
    components: [],
  };
}
